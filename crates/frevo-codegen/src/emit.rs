//! Writing output files, and the header every one of them carries.
//!
//! Three rules, all from `codegen.output.*`, are enforced here rather than
//! left to each emitter:
//!
//! - **LF line endings and no absolute paths**, so the same input produces the
//!   same bytes on Windows and on Linux (`codegen.output.002`).
//! - **A header naming the generator, its version, the package, the package
//!   version and the digest**, and saying that edits are overwritten
//!   (`codegen.output.003`).
//! - **A digest per file**, so a cross-platform comparison can be made on
//!   digests alone (`codegen.output.001`).

use std::path::Path;

use crate::error::{CodegenError, Result};
use crate::inventory::Inventory;
use crate::pin::{GENERATOR_NAME, PackagePin, VERSION_SELECTOR};
use crate::sha256;

/// The generator's own version, so a regeneration by a different generator is
/// visible in the output.
pub const GENERATOR_VERSION: &str = env!("CARGO_PKG_VERSION");

/// One written output file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedFile {
    /// Relative to the run's output directory, with `/` separators.
    pub path: String,
    pub bytes: Vec<u8>,
    /// Lower-case hex SHA-256 of `bytes`.
    pub sha256: String,
}

impl GeneratedFile {
    /// Build a file from its source text, normalising line endings and
    /// computing the digest.
    pub fn new(path: &str, source: &str) -> GeneratedFile {
        let normalised = source.replace("\r\n", "\n").replace('\r', "\n");
        let bytes = normalised.into_bytes();
        GeneratedFile {
            path: path.to_string(),
            sha256: sha256::hex_of(&bytes),
            bytes,
        }
    }

    pub fn text(&self) -> &str {
        std::str::from_utf8(&self.bytes).expect("generated output is built from &str")
    }
}

/// The header every generated file starts with.
///
/// Kept to one function so the five facts `codegen.output.003` requires cannot
/// drift apart between emitters.
pub fn header(pin: &PackagePin) -> String {
    format!(
        "// @generated by {GENERATOR_NAME} {GENERATOR_VERSION} -- do not edit.\n\
         //\n\
         // Source package: {} {}\n\
         // Package SHA-256: {}\n\
         //\n\
         // Every edit to this file is overwritten by the next run of\n\
         // `{GENERATOR_NAME} generate --version {VERSION_SELECTOR}`. A wrong output is fixed\n\
         // in the generator and regenerated, never by editing here.\n",
        pin.name, pin.version, pin.sha256
    )
}

/// The R4 module root.
///
/// It carries the facts tasks 6 and 7 establish — which package was read,
/// which digest was verified, and what the input inventory was — as constants
/// a consumer can assert against, and declares the modules written beside it.
///
/// The emitted source is already in `rustfmt`'s own output form, which is what
/// `codegen.output.004` asserts: a generated file that `cargo fmt --all
/// --check` would rewrite fails the format gate, and a generator cannot shell
/// out to `rustfmt` without making its output depend on the toolchain
/// installed. That is why `SOURCE_PACKAGE_SHA256` is emitted wrapped — the
/// unwrapped line is 106 columns, past the 100-column default.
pub fn module_root(pin: &PackagePin, inventory: &Inventory, modules: &[&str]) -> GeneratedFile {
    let mut declarations = String::new();
    for module in modules {
        declarations.push_str(&format!("pub mod {module};\n"));
    }
    if !declarations.is_empty() {
        declarations.push('\n');
    }
    let source = format!(
        "{header}\n\
         //! The generated R4 model.\n\
         //!\n\
         //! Produced from the StructureDefinitions and SearchParameters of the\n\
         //! pinned FHIR definition package, whose input inventory was:\n\
         //!\n\
         //! - {datatypes} datatype StructureDefinitions\n\
         //! - {resources} resource StructureDefinitions: {concrete} concrete,\n\
         //!   {abstract_count} abstract, {logical} logical\n\
         //! - {parameters} SearchParameter resources\n\
         \n\
         {declarations}\
         /// The FHIR version this module was generated for.\n\
         pub const FHIR_VERSION: &str = \"{version}\";\n\
         \n\
         /// The package the generator read, as `name#version`.\n\
         pub const SOURCE_PACKAGE: &str = \"{name}#{version}\";\n\
         \n\
         /// The SHA-256 of the package directory the generator verified.\n\
         pub const SOURCE_PACKAGE_SHA256: &str =\n\
         \x20   \"{digest}\";\n\
         \n\
         /// Datatype StructureDefinitions read from the package.\n\
         pub const DATATYPE_DEFINITIONS: usize = {datatypes};\n\
         \n\
         /// Resource StructureDefinitions read from the package.\n\
         pub const RESOURCE_DEFINITIONS: usize = {resources};\n\
         \n\
         /// Of those, the concrete resources.\n\
         pub const CONCRETE_RESOURCES: usize = {concrete};\n\
         \n\
         /// SearchParameter resources read from the package.\n\
         pub const SEARCH_PARAMETERS: usize = {parameters};\n",
        header = header(pin),
        datatypes = inventory.datatype_definitions,
        resources = inventory.resource_definitions,
        concrete = inventory.concrete_resources,
        abstract_count = inventory.abstract_resources,
        logical = inventory.logical_resources,
        parameters = inventory.search_parameters,
        version = pin.version,
        name = pin.name,
        digest = pin.sha256,
    );
    GeneratedFile::new("mod.rs", &source)
}

/// Write a run's files under `out_dir`, creating directories as needed.
pub fn write_all(out_dir: &Path, files: &[GeneratedFile]) -> Result<()> {
    for file in files {
        let mut target = out_dir.to_path_buf();
        for part in file.path.split('/') {
            target.push(part);
        }
        if let Some(parent) = target.parent() {
            std::fs::create_dir_all(parent)
                .map_err(|e| CodegenError::other(format!("creating {}: {e}", parent.display())))?;
        }
        std::fs::write(&target, &file.bytes)
            .map_err(|e| CodegenError::other(format!("writing {}: {e}", target.display())))?;
    }
    Ok(())
}
