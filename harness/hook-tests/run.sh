#!/usr/bin/env bash
# Self-tests for the Frevo enforcement hooks.
#
# Each case feeds a hook crafted stdin JSON and asserts the outcome:
#   exit 0 = allow, exit 2 = block.
#
# Every rule has at least one positive (must allow) and one negative (must
# block) case. A hook that never blocks is worse than no hook, because the
# project would be relying on it.
#
# The hooks are run inside a throwaway git repository, with the hook scripts
# copied in, so REPO_ROOT resolves to the sandbox and the real repository is
# never touched. Branch names, fixture files, gate reports and the openspec CLI
# are all controlled per case.
#
# Usage:  bash harness/hook-tests/run.sh [-v]
# Exits non-zero if any case fails. Also run by the hook-selftest CI job.

set -uo pipefail

VERBOSE=0
[ "${1:-}" = "-v" ] && VERBOSE=1

SRC_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SB="$(mktemp -d 2>/dev/null || mktemp -d -t frevo-hooktests)"
trap 'rm -rf "$SB"' EXIT

PASS=0; FAIL=0; FAILED_NAMES=""

PY=""
for p in python3 python py; do command -v "$p" >/dev/null 2>&1 && { PY="$p"; break; }; done
if [ -z "$PY" ]; then echo "FATAL: python3 is required to build test JSON"; exit 1; fi

# --------------------------------------------------------------------------
# Sandbox
# --------------------------------------------------------------------------
setup_sandbox() {
  rm -rf "$SB"; mkdir -p "$SB"
  cp -r "$SRC_ROOT/.claude" "$SB/.claude"
  cd "$SB"
  git init -q -b main
  git config user.email t@example.com
  git config user.name  Test
  git config commit.gpgsign false

  mkdir -p crates/frevo-store/src crates/frevo-model/src docs \
           openspec/specs/store openspec/changes reference oracles gates tasks \
           harness/corpus .github/workflows
  echo "fn main() {}"            > crates/frevo-store/src/lib.rs
  echo "// @generated by codegen" > crates/frevo-model/src/gen.rs
  echo "# spec"                  > openspec/specs/store/spec.md
  echo "pins"                    > reference/PINS.md
  echo "upstream"                > reference/upstream.java
  echo "cases"                   > oracles/suite.json
  echo "name: guard"             > .github/workflows/openspec-guard.yml
  echo "# docs"                  > docs/note.md
  # Ignore gate reports in the sandbox so that writing one neither dirties the
  # tree nor moves HEAD. Both would otherwise make a "red gate" case pass for
  # the wrong reason: the report records a head_sha, so committing it changes
  # the very SHA it refers to.
  printf 'gates/\n'              > .gitignore
  git add -A >/dev/null 2>&1
  git commit -qm "sandbox base" >/dev/null 2>&1

  # A stub `openspec` that succeeds, so cases can isolate the rule under test
  # from whether the real CLI likes the fixture. Cases that need validation to
  # fail call stub_openspec_fail.
  mkdir -p "$SB/bin"
  stub_openspec_ok
  export PATH="$SB/bin:$PATH"
}

stub_openspec_ok() {
  printf '#!/usr/bin/env bash\nexit 0\n' > "$SB/bin/openspec"
  chmod +x "$SB/bin/openspec"
}
stub_openspec_fail() {
  printf '#!/usr/bin/env bash\necho "spec delta missing scenario id" >&2\nexit 1\n' > "$SB/bin/openspec"
  chmod +x "$SB/bin/openspec"
}
remove_openspec() { rm -f "$SB/bin/openspec"; }

# make_change <id> <verdict|-> [tasks_state]
#   tasks_state: open | done | -
make_change() {
  local id="$1" verdict="${2:--}" tasks="${3:--}"
  mkdir -p "openspec/changes/$id"
  cat > "openspec/changes/$id/proposal.md" <<EOF
# $id
EOF
  cat > "openspec/changes/$id/spec.md" <<'EOF'
#### Scenario: [store.create.001] creating a resource assigns a server id
#### Scenario: [store.create.002] creating with a client id is rejected when disallowed
EOF
  [ "$verdict" != "-" ] && printf '%s\n\n1. something\n' "$verdict" > "openspec/changes/$id/review.md"
  case "$tasks" in
    open) printf -- '- [x] write tests\n- [ ] implement\n' > "openspec/changes/$id/tasks.md" ;;
    done) printf -- '- [x] write tests\n- [x] implement\n' > "openspec/changes/$id/tasks.md" ;;
  esac
}

# write_report <id> <green:true|false> <sha|HEAD|stale>
write_report() {
  local id="$1" green="$2" shaspec="$3" sha
  case "$shaspec" in
    HEAD)  sha="$(git rev-parse HEAD)" ;;
    stale) sha="0000000000000000000000000000000000000000" ;;
    *)     sha="$shaspec" ;;
  esac
  mkdir -p "gates/$id"
  printf '{"change":"%s","head_sha":"%s","results":{},"green":%s}\n' "$id" "$sha" "$green" \
    > "gates/$id/report.json"
}

on_branch() { git switch -q -c "$1" 2>/dev/null || git switch -q "$1"; }

commit_all() { git add -A >/dev/null 2>&1; git commit -qm "${1:-wip}" >/dev/null 2>&1; }

# --------------------------------------------------------------------------
# JSON builders
# --------------------------------------------------------------------------
json_edit() { # tool, relpath, content, old, new
  "$PY" -I -c '
import json,sys,os
tool,rel,content,old,new,root = sys.argv[1:7]
ti={"file_path": os.path.join(root, rel)}
if content: ti["content"]=content
if old:     ti["old_string"]=old
if new:     ti["new_string"]=new
print(json.dumps({"hook_event_name":"PreToolUse","tool_name":tool,"tool_input":ti,"cwd":root}))
' "$1" "$2" "${3:-}" "${4:-}" "${5:-}" "$SB"
}

json_bash() { # command
  "$PY" -I -c '
import json,sys
print(json.dumps({"hook_event_name":"PreToolUse","tool_name":"Bash",
                  "tool_input":{"command":sys.argv[1]},"cwd":sys.argv[2]}))
' "$1" "$SB"
}

json_event() { # event, extra_key, extra_val
  "$PY" -I -c '
import json,sys
d={"hook_event_name":sys.argv[1],"cwd":sys.argv[4]}
if sys.argv[2]: d[sys.argv[2]]=(True if sys.argv[3]=="true" else False if sys.argv[3]=="false" else sys.argv[3])
print(json.dumps(d))
' "$1" "${2:-}" "${3:-}" "$SB"
}

# --------------------------------------------------------------------------
# Runner
# --------------------------------------------------------------------------
_run() { # hook, json -> sets RC and OUT
  local hook="$1" json="$2"
  OUT="$(printf '%s' "$json" | bash "$SB/.claude/hooks/$hook" 2>&1)"
  RC=$?
}

check() { # expected_rc, name, hook, json
  local want="$1" name="$2" hook="$3" json="$4"
  _run "$hook" "$json"
  if [ "$RC" -eq "$want" ]; then
    PASS=$((PASS+1))
    [ "$VERBOSE" -eq 1 ] && printf '  ok   %s\n' "$name"
  else
    FAIL=$((FAIL+1)); FAILED_NAMES="$FAILED_NAMES
    - $name (wanted exit $want, got $RC)"
    printf '  FAIL %s -- wanted exit %s, got %s\n' "$name" "$want" "$RC"
    printf '%s\n' "$OUT" | head -6 | sed 's/^/         | /'
  fi
}
expect_block() { check 2 "$@"; }
expect_allow() { check 0 "$@"; }

# --------------------------------------------------------------------------
# Linked worktrees
# --------------------------------------------------------------------------
# The cases above run the hooks from the sandbox root, which is also the repo
# root, so a hook that derives its root from its own location looks correct.
# That is precisely how the REPO_ROOT bug survived: in the real layout the hook
# scripts sit in the PRIMARY worktree while the session edits a LINKED one, and
# the two are different repositories as far as `git -C` is concerned.
#
# _run_at runs the primary worktree's hook with the working directory in the
# linked one. Any hook rule that depends on the branch, the active change or a
# relative path has to come out right there, or it is enforcing against a tree
# nobody is editing.
_run_at() { # dir, hook, json -> sets RC and OUT
  local dir="$1" hook="$2" json="$3"
  OUT="$(cd "$dir" && printf '%s' "$json" | bash "$SB/.claude/hooks/$hook" 2>&1)"
  RC=$?
}

check_at() { # dir, expected_rc, name, hook, json
  local dir="$1" want="$2" name="$3" hook="$4" json="$5"
  _run_at "$dir" "$hook" "$json"
  if [ "$RC" -eq "$want" ]; then
    PASS=$((PASS+1))
    [ "$VERBOSE" -eq 1 ] && printf '  ok   %s
' "$name"
  else
    FAIL=$((FAIL+1)); FAILED_NAMES="$FAILED_NAMES
    - $name (wanted exit $want, got $RC)"
    printf '  FAIL %s -- wanted exit %s, got %s
' "$name" "$want" "$RC"
    printf '%s
' "$OUT" | head -6 | sed 's/^/         | /'
  fi
}
expect_block_at() { check_at "$1" 2 "${@:2}"; }
expect_allow_at()  { check_at "$1" 0 "${@:2}"; }

# Add a linked worktree on a change branch carrying its own approved change.
# Echoes the worktree path. WT is also set, for readability at the call sites.
# json_edit builds the file path against $SB. In a worktree case the file has to
# be inside the worktree, or the hook is being asked about a path in a different
# tree and correctly finds no rule that applies.
json_edit_at() { # root, tool, relpath, content, [cwd, default root]
  "$PY" -I -c '
import json,sys,os
root,tool,rel,content,cwd = sys.argv[1:6]
ti={"file_path": os.path.join(root, rel)}
if content: ti["content"]=content
print(json.dumps({"hook_event_name":"PreToolUse","tool_name":tool,"tool_input":ti,"cwd":cwd or root}))
' "$1" "$2" "$3" "${4:-}" "${5:-}"
}

add_worktree() { # id [verdict]
  local id="$1" verdict="${2:-APPROVED}"
  WT="$SB-wt-$id"
  rm -rf "$WT"
  git worktree add -q -b "change/$id" "$WT" >/dev/null 2>&1
  ( cd "$WT" && make_change "$id" "$verdict" open )
  printf '%s' "$WT"
}

# json_event with the payload's cwd pointing somewhere other than the hook
# process's working directory. Claude Code reports the session's current
# directory in "cwd"; the hook process may have been started elsewhere.
json_event_at() { # cwd, event, extra_key, extra_val
  "$PY" -I -c '
import json,sys
d={"hook_event_name":sys.argv[2],"cwd":sys.argv[1]}
if sys.argv[3]: d[sys.argv[3]]=sys.argv[4]
print(json.dumps(d))
' "$1" "$2" "${3:-}" "${4:-}"
}

